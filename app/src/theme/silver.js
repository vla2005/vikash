const createTheme = (scheme, palette, effects) => ({
  ...themes[scheme],
  variant: 'silver',
  colors: palette,
  effects,
  typography: Object.fromEntries(
    Object.entries(themes[scheme].typography).map(([key, value]) => [
      key,
      { ...value, color: key === 'title' ? palette.text : palette.secondary },
    ]),
  ),
});

