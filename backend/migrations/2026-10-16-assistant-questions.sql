-- Recepção de perguntas. Não altera tabelas nem valores financeiros.
-- Aplicar antes de iniciar a versão com AssistantQuestionService.
BEGIN;
CREATE TABLE IF NOT EXISTS assistant_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_id VARCHAR(80) NOT NULL,
    title VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_assistant_conversation_client UNIQUE(user_id, client_id)
);
CREATE TABLE IF NOT EXISTS assistant_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    conversation_id BIGINT NOT NULL REFERENCES assistant_conversations(id) ON DELETE CASCADE,
    client_id VARCHAR(80) NOT NULL,
    role VARCHAR(16) NOT NULL,
    content VARCHAR(6000) NOT NULL,
    status VARCHAR(24) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_assistant_message_client UNIQUE(conversation_id, client_id)
);
COMMIT;
